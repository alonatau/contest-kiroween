/* =========================================================================
   font.js — a tiny 3x5 dot-matrix font for the LCD.
   Each glyph is 3 wide x 5 tall. '#' = on, '.' = off.
   Exposes: Font.glyphs  -> { char: ["...","...","...","...","..."] }
            Font.width   -> 3
            Font.height  -> 5
   ========================================================================= */

const Font = (function () {
  const g = {};
  const def = function (s, rows) { g[s] = rows; };

  // Uppercase letters
  def("A", [".#.", "#.#", "###", "#.#", "#.#"]);
  def("B", ["##.", "#.#", "##.", "#.#", "##."]);
  def("C", [".##", "#..", "#..", "#..", ".##"]);
  def("D", ["##.", "#.#", "#.#", "#.#", "##."]);
  def("E", ["###", "#..", "##.", "#..", "###"]);
  def("F", ["###", "#..", "##.", "#..", "#.."]);
  def("G", [".##", "#..", "#.#", "#.#", ".##"]);
  def("H", ["#.#", "#.#", "###", "#.#", "#.#"]);
  def("I", ["###", ".#.", ".#.", ".#.", "###"]);
  def("J", ["..#", "..#", "..#", "#.#", ".##"]);
  def("K", ["#.#", "#.#", "##.", "#.#", "#.#"]);
  def("L", ["#..", "#..", "#..", "#..", "###"]);
  def("M", ["#.#", "###", "###", "#.#", "#.#"]);
  def("N", ["#.#", "##.", "##.", "##.", "#.#"]);
  def("O", [".#.", "#.#", "#.#", "#.#", ".#."]);
  def("P", ["##.", "#.#", "##.", "#..", "#.."]);
  def("Q", [".#.", "#.#", "#.#", "#.#", ".##"]);
  def("R", ["##.", "#.#", "##.", "#.#", "#.#"]);
  def("S", [".##", "#..", ".#.", "..#", "##."]);
  def("T", ["###", ".#.", ".#.", ".#.", ".#."]);
  def("U", ["#.#", "#.#", "#.#", "#.#", ".#."]);
  def("V", ["#.#", "#.#", "#.#", ".#.", ".#."]);
  def("W", ["#.#", "#.#", "###", "###", "#.#"]);
  def("X", ["#.#", "#.#", ".#.", "#.#", "#.#"]);
  def("Y", ["#.#", "#.#", ".#.", ".#.", ".#."]);
  def("Z", ["###", "..#", ".#.", "#..", "###"]);

  // Digits
  def("0", [".#.", "#.#", "#.#", "#.#", ".#."]);
  def("1", [".#.", "##.", ".#.", ".#.", "###"]);
  def("2", [".#.", "..#", ".#.", "#..", "###"]);
  def("3", ["###", "..#", ".##", "..#", "###"]);
  def("4", ["#.#", "#.#", "###", "..#", "..#"]);
  def("5", ["###", "#..", "###", "..#", "###"]);
  def("6", [".#.", "#..", "###", "#.#", ".#."]);
  def("7", ["###", "..#", ".#.", ".#.", "#.."]);
  def("8", [".#.", "#.#", ".#.", "#.#", ".#."]);
  def("9", [".#.", "#.#", "###", "..#", ".#."]);

  // Punctuation / symbols
  def(" ", ["...", "...", "...", "...", "..."]);
  def(".", ["...", "...", "...", ".#.", "..."]);
  def(",", ["...", "...", "...", ".#.", "#.."]);
  def("!", [".#.", ".#.", ".#.", "...", ".#."]);
  def("?", ["###", "..#", ".#.", "...", ".#."]);
  def(":", ["...", ".#.", "...", ".#.", "..."]);
  def("-", ["...", "...", "###", "...", "..."]);
  def("/", ["..#", ".#.", ".#.", ".#.", "#.."]);
  def("'", [".#.", "#..", "...", "...", "..."]);
  def("<", [".#.", "#..", "#..", "#..", ".#."]);
  def(">", [".#.", "..#", "..#", "..#", ".#."]);

  return {
    glyphs: g,
    width: 3,
    height: 5,
    // advance width: glyph + 1px gap; allows 8 chars across 32px (8*3 + 7*1 = 31)
    advance: 4,
  };
})();
